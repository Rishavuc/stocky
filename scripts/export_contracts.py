"""Generate API request contracts from FastAPI's actual OpenAPI schema."""

import sys, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.main import app

schema = app.openapi()
(ROOT / "frontend/src/openapi.json").write_text(json.dumps(schema, indent=2))


def ts(s):
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(json.dumps(x) for x in s["enum"])
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    t = s.get("type")
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        return "(" + ts(s["items"]) + ")[]"
    if t == "object":
        if not s.get("properties"):
            return "Record<string, " + ts(s.get("additionalProperties", {})) + ">"
        req = s.get("required", [])
        return (
            "{ "
            + "; ".join(
                json.dumps(k) + ("" if k in req else "?") + ": " + ts(v)
                for k, v in s["properties"].items()
            )
            + " }"
        )
    if t == "string":
        return "string"
    return "unknown"


lines = ["// Generated by scripts/export_contracts.py. Do not edit by hand."]
for name, s in schema.get("components", {}).get("schemas", {}).items():
    lines.append("export type " + name + " = " + ts(s) + ";")
(ROOT / "frontend/src/contracts.ts").write_text("\n".join(lines) + "\n")
print("Generated", len(lines) - 1, "API contracts")
